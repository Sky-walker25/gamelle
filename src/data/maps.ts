/** Towers available before winning any map. */
export const DEFAULT_TOWERS = ['archers', 'ballista', 'fire'];

export function mapDef(id: string): MapDef {
  const m = MAP_BY_ID[id];
  if (!m) throw new Error(`Unknown map ${id}`);
  return m;
}
