const DICTS: Record<Lang, Record<I18nKey, string>> = { fr, en };

let current: Lang = 'fr';
const listeners = new Set<(lang: Lang) => void>();

export function getLang(): Lang {
  return current;
}

export function setLang(lang: Lang): void {
  if (lang === current) return;
  current = lang;
  document.documentElement.lang = lang;
  for (const l of listeners) l(lang);
}

export function onLangChange(listener: (lang: Lang) => void): () => void {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

/** Translate a UI key with `{param}` substitutions. */
export function t(key: I18nKey, params?: Record<string, string | number>): string {
  let text = DICTS[current][key] ?? DICTS.fr[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) text = text.replaceAll(`{${k}}`, String(v));
  }
  return text;
}

/** Translate a dynamically composed key (e.g. `'era.' + era`). */
export function tk(key: string, params?: Record<string, string | number>): string {
  return t(key as I18nKey, params);
}

/** Pick the current language from a localised data field. */
export function L(text: LocalizedText): string {
  return text[current] ?? text.fr;
}

export function formatDuration(seconds: number): string {
  const s = Math.floor(seconds % 60);
  const m = Math.floor(seconds / 60) % 60;
  const h = Math.floor(seconds / 3600);
  const mm = String(m).padStart(2, '0');
  const ss = String(s).padStart(2, '0');
  return h > 0 ? `${h}:${mm}:${ss}` : `${m}:${ss}`;
}

/** The game defaults to French; players can switch to English at any time. */
export function detectLang(): Lang {
  return 'fr';
}
